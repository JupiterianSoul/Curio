ACC = {
    'grave': ['#.', '.#'],
    'acute': ['.#', '#.'],
    'circ': ['.#.', '#.#'],
    'tilde': ['.#.#', '#.#.'],
    'diaer': ['#.#', '...'],
    'ring': ['.#.', '#.#'],
}

COMPOSE = {
    'À': ('A', 'grave'), 'Á': ('A', 'acute'), 'Â': ('A', 'circ'), 'Ã': ('A', 'tilde'), 'Ä': ('A', 'diaer'), 'Å': ('A', 'ring'),
    'È': ('E', 'grave'), 'É': ('E', 'acute'), 'Ê': ('E', 'circ'), 'Ë': ('E', 'diaer'),
    'Ì': ('I', 'grave'), 'Í': ('I', 'acute'), 'Î': ('I', 'circ'), 'Ï': ('I', 'diaer'),
    'Ñ': ('N', 'tilde'),
    'Ò': ('O', 'grave'), 'Ó': ('O', 'acute'), 'Ô': ('O', 'circ'), 'Õ': ('O', 'tilde'), 'Ö': ('O', 'diaer'),
    'Ù': ('U', 'grave'), 'Ú': ('U', 'acute'), 'Û': ('U', 'circ'), 'Ü': ('U', 'diaer'),
    'Ý': ('Y', 'acute'), 'Ÿ': ('Y', 'diaer'),
    'à': ('a', 'grave'), 'á': ('a', 'acute'), 'â': ('a', 'circ'), 'ã': ('a', 'tilde'), 'ä': ('a', 'diaer'), 'å': ('a', 'ring'),
    'è': ('e', 'grave'), 'é': ('e', 'acute'), 'ê': ('e', 'circ'), 'ë': ('e', 'diaer'),
    'ì': ('ı', 'grave'), 'í': ('ı', 'acute'), 'î': ('ı', 'circ'), 'ï': ('ı', 'diaer'),
    'ñ': ('n', 'tilde'),
    'ò': ('o', 'grave'), 'ó': ('o', 'acute'), 'ô': ('o', 'circ'), 'õ': ('o', 'tilde'), 'ö': ('o', 'diaer'),
    'ù': ('u', 'grave'), 'ú': ('u', 'acute'), 'û': ('u', 'circ'), 'ü': ('u', 'diaer'),
    'ý': ('y', 'acute'), 'ÿ': ('y', 'diaer'),
}


def compose():
    for ch, (base, acc) in COMPOSE.items():
        rows, _ = G[base]
        lower = base.islower() or base == 'ı'
        a = ACC[acc]
        w = max(len(rows[0]), len(a[0]))
        bo = (w - len(rows[0])) // 2
        ao = (w - len(a[0]) + (1 if len(rows[0]) % 2 == 0 and len(a[0]) % 2 == 1 else 0)) // 2
        ao = max(0, min(ao, w - len(a[0])))
        body = ['.' * bo + r + '.' * (w - bo - len(r)) for r in rows]
        accent = ['.' * ao + r + '.' * (w - ao - len(r)) for r in a]
        if lower:
            out = [accent[i] if i < 2 and '#' not in body[i] else body[i] for i in range(len(body))]
            for i in range(2):
                if '#' in body[i]:
                    out[i] = ''.join('#' if (x == '#' or y == '#') else '.' for x, y in zip(body[i], accent[i]))
            G[ch] = (out, 0)
        else:
            G[ch] = (accent + body, -2)
    rows, _ = G['C']
    G['Ç'] = (rows + ['..#..', '.#...'], 0)
    rows, _ = G['c']
    G['ç'] = (rows + ['..#.', '.#..'], 0)


compose()
